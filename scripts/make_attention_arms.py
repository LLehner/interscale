r"""Write a sweep arms file: every attention backend x encoding combination the config accepts.

Each combination of ``--backend``, ``--node``, ``--bias`` and ``--rotary`` is validated on the base
config; the ones that pass become arms, the rest are listed in the file's header with the
validator's reason. Run the result with ``main_sweep.py --sweep_cfg <file> --sweep_goal hyperparmeter``
and the same base config (attention_plan.md, "Test matrix")::

    python scripts/make_attention_arms.py --cfg base.yaml \
        --backend dense --backend performer --backend linear:attention.head_dim=32 --backend exphormer \
        --node none --node lap --bias none --bias fourier --bias spectral --rotary none --rotary rope \
        --seeds 0 1 2 --out attention_arms.yaml

``--backend`` is ``[label=]kind[:key=value,...]``: settings are dotted keys relative to
``model.global_component.parameters`` (or full paths), values Python literals or YAML; a label tells
two settings of one backend apart (``wide=linear:attention.head_dim=64``). Encoding levels are
``none`` or names joined by ``+`` (``lap+rw``). ``--grid model.n_embed=64,128`` adds a plain sweep
parameter crossed with every arm; an arm is kept only if it validates at every grid point. Without
``--backend``, every registered backend is crossed.
"""

import argparse
import sys
from pathlib import Path

from interscale.config.cli import add_config_args
from interscale.config.sweep import arms_yaml, generate_arms, parse_grid


def base_config(args, parser):
    """The base config as (paths, overrides): one ``--cfg`` file or a registry pair, as main_sweep takes."""
    from interscale.config.registry import resolve_config_paths

    using_registry = args.dataset is not None or args.task is not None
    if args.cfg is not None and using_registry:
        parser.error("--cfg cannot be combined with --dataset/--task.")
    if args.cfg is not None:
        return [args.cfg], []
    if args.dataset is None or args.task is None:
        parser.error("give either --dataset and --task, or --cfg.")
    return resolve_config_paths(args.dataset, args.task, registry_path=args.registry)


def main(argv=None):
    from interscale.module.global_modules.attention import ATTENTION_REGISTRY

    parser = add_config_args(argparse.ArgumentParser(description=__doc__.splitlines()[0]))
    parser.add_argument("--backend", action="append", default=None, help="[label=]kind[:key=value,...]; repeatable.")
    parser.add_argument("--node", action="append", default=None, help="node encodings, e.g. none, lap, lap+rw.")
    parser.add_argument("--bias", action="append", default=None, help="attention biases, e.g. none, fourier.")
    parser.add_argument("--rotary", action="append", default=None, help="rotary encodings, e.g. none, rope.")
    parser.add_argument("--grid", action="append", default=[], help="key=v1,v2,...: a sweep parameter; repeatable.")
    parser.add_argument("--seeds", type=int, nargs="+", default=[0], help="optim.seed values to grid over.")
    parser.add_argument("--out", type=Path, default=None, help="Where to write the yaml (default: stdout).")
    args = parser.parse_args(argv)

    paths, overrides = base_config(args, parser)
    generated = generate_arms(
        paths,
        overrides,
        backends=args.backend or sorted(ATTENTION_REGISTRY),
        node=args.node or ["none"],
        bias=args.bias or ["none"],
        rotary=args.rotary or ["none"],
        grid=dict(parse_grid(spec) for spec in args.grid),
    )
    command = " ".join(["scripts/make_attention_arms.py", *(sys.argv[1:] if argv is None else argv)])
    text = arms_yaml(generated, seeds=args.seeds, header=[f"Generated by: {command}"])
    if args.out is None:
        sys.stdout.write(text)
    else:
        args.out.write_text(text)
        print(
            f"wrote {len(generated.arms)} arms to {args.out} ({len(generated.rejected)} combinations rejected)",
            file=sys.stderr,
        )
    return generated


if __name__ == "__main__":
    main()
